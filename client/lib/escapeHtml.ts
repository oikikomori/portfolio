/** Escapes HTML special characters before interpolating untrusted/semi-trusted
 *  text into an HTML string (email templates, server-rendered fragments). */
export function escapeHtml(input: string): string {
  return input
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
